/*
 * Offset 0x00, Controller Capabilities. Read only. TO counts 500ms units,
 * MPSMIN and MPSMAX are exponents of 4KB.
 */
typedef union
{
    struct
    {
        ULONGLONG MQES:16;
        ULONGLONG CQR:1;
        /* CAP.AMS occupies bits 17 and 18 */
        ULONGLONG AMS_WeightedRoundRobinWithUrgent:1;
        ULONGLONG AMS_VendorSpecific:1;
        ULONGLONG Reserved0:5;
        ULONGLONG TO:8;
        ULONGLONG DSTRD:4;
        ULONGLONG NSSRS:1;
        /* CAP.CSS occupies bits 37 to 44 */
        ULONGLONG CSS_NVM:1;
        ULONGLONG CSS_Reserved0:1;
        ULONGLONG CSS_Reserved1:1;
        ULONGLONG CSS_Reserved2:1;
        ULONGLONG CSS_Reserved3:1;
        ULONGLONG CSS_Reserved4:1;
        ULONGLONG CSS_MultipleIo:1;
        ULONGLONG CSS_AdminOnly:1;
        ULONGLONG BPS:1;
        ULONGLONG CPS:2;
        ULONGLONG MPSMIN:4;
        ULONGLONG MPSMAX:4;
        ULONGLONG PMRS:1;
        ULONGLONG CMBS:1;
        ULONGLONG NSSS:1;
        ULONGLONG CRWMS:1;
        ULONGLONG CRIMS:1;
        ULONGLONG Reserved2:3;
    } DUMMYSTRUCTNAME;
    ULONGLONG AsUlonglong;
} NVME_CONTROLLER_CAPABILITIES, *PNVME_CONTROLLER_CAPABILITIES;

