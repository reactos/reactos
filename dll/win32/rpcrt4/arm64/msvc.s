//
// The stubless proxy thunks put the method index in w16. The arguments go
// to ndr_stubless_client_call as the integer and the floating point
// register blocks.
//
    NESTED_ENTRY call_stubless_func
    stp     x29, x30, [sp, #-0x90]!
    mov     x29, sp
    stp     d0, d1, [sp, #0x10]
    stp     d2, d3, [sp, #0x20]
    stp     d4, d5, [sp, #0x30]
    stp     d6, d7, [sp, #0x40]
    stp     x0, x1, [sp, #0x50]
    stp     x2, x3, [sp, #0x60]
    stp     x4, x5, [sp, #0x70]
    stp     x6, x7, [sp, #0x80]
    mov     w0, w16
    add     x1, sp, #0x50
    add     x2, sp, #0x10
    bl      ndr_stubless_client_call
    ldp     x29, x30, [sp], #0x90
    ret
LABEL(call_stubless_func_end)
    NESTED_END call_stubless_func

//
// LONG_PTR
// call_server_func(
//     SERVER_ROUTINE func,
//     unsigned char *args,
//     unsigned int stack_size,
//     const NDR_PROC_PARTIAL_OIF_HEADER *header);
//
// args_stack_to_regs fills the register block at sp and the stack arguments
// above it, the block is then popped into x0-x7 and d0-d7.
//
    NESTED_ENTRY call_server_func
    stp     x29, x30, [sp, #-0x20]!
    stp     x19, x20, [sp, #0x10]
    mov     x29, sp
    mov     w2, w2
    add     x9, x2, #(16 * 8 + 15)
    lsr     x9, x9, #4
    sub     sp, sp, x9, uxtx #4
    mov     x19, x0
    mov     x0, x1
    mov     x1, sp
    add     x2, sp, #(16 * 8)
    bl      args_stack_to_regs
    ldp     x2, x3, [sp, #0x10]
    ldp     x4, x5, [sp, #0x20]
    ldp     x6, x7, [sp, #0x30]
    ldp     d0, d1, [sp, #0x40]
    ldp     d2, d3, [sp, #0x50]
    ldp     d4, d5, [sp, #0x60]
    ldp     d6, d7, [sp, #0x70]
    ldp     x0, x1, [sp], #0x80
    blr     x19
    mov     sp, x29
    ldp     x19, x20, [sp, #0x10]
    ldp     x29, x30, [sp], #0x20
    ret
LABEL(call_server_func_end)
    NESTED_END call_server_func

//
// The client call entry points store the variadic registers next to the
// caller's stack arguments, so the workers see one argument array.
//
    NESTED_ENTRY NdrClientCall2
    stp     x29, x30, [sp, #-0x40]!
    stp     x2, x3, [sp, #0x10]
    stp     x4, x5, [sp, #0x20]
    stp     x6, x7, [sp, #0x30]
    add     x2, sp, #0x10
    mov     x3, #0
    bl      NdrpClientCall2
    ldp     x29, x30, [sp], #0x40
    ret
LABEL(NdrClientCall2_end)
    NESTED_END NdrClientCall2

    NESTED_ENTRY NdrAsyncClientCall
    stp     x29, x30, [sp, #-0x40]!
    stp     x2, x3, [sp, #0x10]
    stp     x4, x5, [sp, #0x20]
    stp     x6, x7, [sp, #0x30]
    add     x2, sp, #0x10
    mov     x3, #0
    bl      ndr_async_client_call
    ldp     x29, x30, [sp], #0x40
    ret
LABEL(NdrAsyncClientCall_end)
    NESTED_END NdrAsyncClientCall

    NESTED_ENTRY NdrClientCall3
    stp     x29, x30, [sp, #-0x40]!
    str     x3, [sp, #0x18]
    stp     x4, x5, [sp, #0x20]
    stp     x6, x7, [sp, #0x30]
    add     x3, sp, #0x18
    bl      ndr64_client_call
    ldp     x29, x30, [sp], #0x40
    ret
LABEL(NdrClientCall3_end)
    NESTED_END NdrClientCall3

    NESTED_ENTRY Ndr64AsyncClientCall
    stp     x29, x30, [sp, #-0x40]!
    str     x3, [sp, #0x18]
    stp     x4, x5, [sp, #0x20]
    stp     x6, x7, [sp, #0x30]
    add     x3, sp, #0x18
    mov     x4, #0
    bl      ndr64_async_client_call
    ldp     x29, x30, [sp], #0x40
    ret
LABEL(Ndr64AsyncClientCall_end)
    NESTED_END Ndr64AsyncClientCall

//
// Thunks for the methods past IUnknown. Every stubless client thunk has the
// same size, cproxy.c derives the table layout from the first two.
//
    MACRO
    STUBLESS_THUNK $num
    LEAF_ENTRY ObjectStublessClient$num
    mov     w16, #$num
    b       call_stubless_func
    LEAF_END ObjectStublessClient$num
    MEND

    MACRO
    FORWARDING_THUNK $num
    LEAF_ENTRY NdrProxyForwardingFunction$num
    ldr     x0, [x0, #0x20]
    ldr     x16, [x0]
    ldr     x16, [x16, #($num * 8)]
    br      x16
    LEAF_END NdrProxyForwardingFunction$num
    MEND

